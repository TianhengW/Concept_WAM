#!/usr/bin/env bash
# Generate hydra dirs yaml files for RoboCasa365 (pretrain Human300 + target splits).
# LeRobot roots live at <task>/<date>/lerobot/lerobot (double "lerobot" level);
# MimicGen roots live under mg/ and are EXCLUDED from the Human300 pretrain set.
# Re-run after the tar extraction finishes to pick up all tasks.
set -euo pipefail

REPO=/storage/yukaichengLab/mazijian/wth/action-as-patch-robocasa
DATA=/storage/yukaichengLab/share/datasets/robocasa365
OUT=${REPO}/configs/data
PY=${PYTHON:-python3}

gen() {
  local src=$1 out=$2 pkg=$3
  local tmp
  tmp=$(mktemp)
  "${PY}" "${REPO}/scripts/data/collect_lerobot_roots.py" "${src}" --key "" > "${tmp}"
  {
    echo "# @package ${pkg}"
    echo "# generated by experiments/robocasa/gen_dirs.sh on $(date +%F) from ${src}"
    echo "dataset_dirs:"
    grep -v "/mg/" "${tmp}" | sed "s/^- /  - /"
  } > "${out}"
  rm -f "${tmp}"
  echo "${out}: $(grep -c "^  - " "${out}") roots"
}

# pretrain Human300 = atomic(65) + composite(235), mg/ excluded
tmp_all=$(mktemp)
"${PY}" "${REPO}/scripts/data/collect_lerobot_roots.py" "${DATA}/pretrain" --key "" | grep -v "/mg/" > "${tmp_all}"
{
  echo "# @package _group_"
  echo "# generated by experiments/robocasa/gen_dirs.sh on $(date +%F): pretrain Human300 (mg/ excluded)"
  echo "dataset_dirs:"
  sed "s/^- /  - /" "${tmp_all}"
} > "${OUT}/robocasa365_pretrain_dirs.yaml"
echo "robocasa365_pretrain_dirs.yaml: $(grep -c '^  - ' "${OUT}/robocasa365_pretrain_dirs.yaml") roots (expect 300 when extraction completes)"
rm -f "${tmp_all}"

# target atomic-seen (18 tasks)
tmp_a=$(mktemp)
"${PY}" "${REPO}/scripts/data/collect_lerobot_roots.py" "${DATA}/target/atomic" --key "" | grep -v "/mg/" > "${tmp_a}"
{
  echo "# @package _group_"
  echo "dataset_dirs:"
  sed "s/^- /  - /" "${tmp_a}"
} > "${OUT}/robocasa365_target_atomic_dirs.yaml"
echo "robocasa365_target_atomic_dirs.yaml: $(grep -c '^  - ' "${OUT}/robocasa365_target_atomic_dirs.yaml") roots (expect 18)"
rm -f "${tmp_a}"

# target composite seen/unseen: needs the official 16/16 task lists.
# Put the task names (one per line) into seen_tasks.txt / unseen_tasks.txt next to
# this script, then re-run. Source: RoboCasa365 official repo / HF collection.
DIR_SELF=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
for split in seen unseen; do
  list="${DIR_SELF}/${split}_tasks.txt"
  out="${OUT}/robocasa365_target_composite_${split}_dirs.yaml"
  if [[ -f "${list}" ]]; then
    {
      echo "# @package _group_"
      echo "dataset_dirs:"
      while IFS= read -r t; do
        [[ -z "${t}" ]] && continue
        root=$("${PY}" "${REPO}/scripts/data/collect_lerobot_roots.py" "${DATA}/target/composite/${t}" --key "" | grep -v "/mg/" | head -1 | sed "s/^- //")
        [[ -n "${root}" ]] && echo "  - ${root}"
      done < "${list}"
    } > "${out}"
    echo "${out}: $(grep -c '^  - ' "${out}") roots (expect 16)"
  else
    echo "SKIP composite-${split}: ${list} not found (need official task list)"
  fi
done
